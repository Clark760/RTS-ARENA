// 弑君歼灭玩法给 bot 的目标信息（这个文件也会原样进 arena.d.ts）

export interface Objectives {
  /** 各个对手主基地（base）开局时的左上角位置；基地不会移动，被摧毁后仍然列在这里 */
  enemyBases: { owner: number; x: number; y: number }[]
  /** 每个玩家的击杀价值，下标是玩家编号；到时间上限时比这个 */
  killValue: number[]
  /**
   * 地图上的野怪营地（位置公开，和金矿一样；看不见的营地里活着几只也告诉你）。打死一只野怪，最后一击的玩家得 150 金赏金；
   * 每 900 tick（第 900、1800……tick）把死掉的野怪原地补满（营地没清空也补）。野怪挨了打、或者你的东西走进营地 2 格内就会出手，追打营地 8 格内的玩家实体
   * （8 格按目标离营地算，野怪自己绕路去追时可能走到 10 多格外）
   */
  creepCamps: {
    /** 营地第一只野怪的位置 */
    x: number
    y: number
    /** 营地的每一格（满员时每格站一只；地图左下那一侧的营地往右、往下长，中心对称的右上那一侧往左、往上长） */
    cells: { x: number; y: number }[]
    /** 正在出手：挨了打、或者有玩家的东西进了营地 2 格内，营地 8 格内还有玩家的东西 */
    angry: boolean
    /** 满员几只 */
    size: number
    /** 现在活着几只 */
    alive: number
    /** 有死掉的野怪时，下一次刷新在第几 tick（900 的整数倍）；满员是 null */
    respawnAt: number | null
  }[]
  /** 每个玩家到现在拿到的野怪赏金，下标是玩家编号；到时间上限时击杀价值、主基地生命都一样就比这个 */
  creepBounty: number[]
  /**
   * 中央宝箱（看不见也告诉你）：每 900 tick 在地图正中两个中心对称的格子上各刷一个（1×1，那个位置的还在就不刷），300 血、不会动、不会还手，
   * 打掉一个（最后一击）的玩家马上得 300 金，不算击杀价值。正中被挡住的地图换成离正中最近、中心对称的一对格子。
   * 刷新那一刻宝箱的格子上站着谁的单位，谁就直接捡到这个宝箱（得金子，宝箱不刷出来）；每一方每轮最多直接捡一个，
   * 两格都站着同一方的单位，只捡 spots 里排在前面的那个，另一格等它走开再刷出宝箱；站着野怪也等它走开再刷
   */
  treasure: {
    /** 现在在场的宝箱：格子（1×1）、剩余生命、打掉得多少金 */
    chests: { x: number; y: number; hp: number; gold: number }[]
    /** 两个宝箱的格子（在不在场都列出来） */
    spots: { x: number; y: number }[]
    /** 下一次刷新在第几 tick（900 的整数倍） */
    nextAt: number
  }
}
